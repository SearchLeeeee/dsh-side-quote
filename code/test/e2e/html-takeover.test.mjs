scenario('E-16 闸门关闭：点击开关恰一条 error、正文不接管、开关禁用并说明原因', async (page, shot) => {
  await setDeveloperTools(page, true)
  await prepareHtmlPreview(page, { takeover: null })
  await waitForBuiltinBody(page)
  const openState = await waitForHtmlToggle(page, { pressed: false, disabled: false })
  const enabledHint = openState.hint

  let failure
  try {
    // Close the platform script gate inside the instance, then ask for the takeover.
    const gate = await setDeveloperTools(page, false)
    assert.equal(gate.enabled, false, 'the settings switch must now read as false')
    const noticesBefore = await readNotices(page)
    page.resetConsoleErrors()
    await activate(page, markedControlExpression(HTML_MARKERS.toggle), 'the HTML takeover toggle')

    const added = await waitForAddedNotices(page, noticesBefore)
    assert.equal(added.filter(isErrorNotice).length, 1, `exactly one error must explain the refused takeover: ${JSON.stringify(added)}`)
    assert.equal(added.filter(isInfoNotice).length, 0, `a refused takeover must not also report success: ${JSON.stringify(added)}`)

    const pressed = await waitForHtmlToggle(page, { pressed: true, disabled: true })
    assert.notEqual(pressed.hint, '', 'the disabled toggle must carry a readable reason, not just look grey')
    assert.notEqual(pressed.hint, enabledHint, 'the disabled state must state a reason that the enabled state does not')

    // The reason must be in the accessibility tree, not only in a `title` whose
    // tooltip a `disabled` control may never show.
    const description = await readToggleDescription(page)
    assert.notEqual(description, '', 'the disabled toggle must describe its reason in the DOM')
    assert.equal(pressed.hint.includes(description), true, 'the described text is the reason the toggle exposes')

    await new Promise((resolve) => setTimeout(resolve, 900))
    assert.equal(await countElements(page, TAKEOVER_BODY), 0, 'no takeover body may be registered while the gate is closed')
    assert.equal(await countElements(page, TAKEOVER_FRAME), 0, 'no takeover frame may exist while the gate is closed')
    const settled = noticesAdded(noticesBefore, await readNotices(page))
    assert.equal(settled.filter(isInfoNotice).length, 0, `a refused takeover must not report success: ${JSON.stringify(settled)}`)
    assert.equal(settled.filter(isErrorNotice).length, 1, `the refusal must stay at exactly one error: ${JSON.stringify(settled)}`)
    const body = await readHtmlBodyState(page)
    assert.equal(body.builtin.length, 1, 'the built-in renderer must keep the body on a closed gate')
    assert.deepEqual(page.consoleErrors, [], `console errors during E-16: ${JSON.stringify(page.consoleErrors)}`)
    await shot('E-16-1-gate-closed', { takeover: 'off', iframeSandbox: sandboxOf(body), developerTools: false })
  } catch (error) {
    failure = error
    throw error
  } finally {
    // Leave the gate open for the following cases; a restore failure must not
    // hide this case's own verdict.
    try {
      await setDeveloperTools(page, true)
      await setHtmlTakeover(page, null, { reload: false })
    } catch (error) {
      if (failure === undefined) throw error
    }
  }
})

