/**
 * Run one test against a fresh page, closing it afterwards.
 * @param {string} name - test name.
 * @param {(page: object, shot: (label: string, options?: object) => Promise<string>) => Promise<void>} body - test body.
 */
function scenario(name, body) {
  test(name, { skip: skipReason }, async () => {
    const page = await openPage(browser, config.baseUrl)
    try {
      await body(page, (label, options) => page.screenshot(label, evidence, options))
    } finally {
      await page.close()
    }
  })
}

/** Collapse rendering whitespace so a quote can be compared with a selection. */
function collapse(text) {
  return String(text).replace(/\s+/gu, ' ').trim()
}

/**
 * Read the text assistive technology receives from the toggle's
 * `aria-describedby` target. A `disabled` control's native `title` tooltip is
 * browser behaviour and invisible to a screenshot, so the DOM is read instead.
 * @param {object} page - the page.
 * @returns {Promise<string>} the described text, or '' when nothing is described.
 */
async function readToggleDescription(page) {
  return page.evaluate(`(() => {
    const toggle = [...document.querySelectorAll('[${HTML_MARKERS.toggle}]')]
      .find((candidate) => candidate.getClientRects().length > 0) || null;
    if (toggle === null) return '';
    const ids = (toggle.getAttribute('aria-describedby') || '').split(/\\s+/u).filter((id) => id !== '');
    return ids.map((id) => {
      const node = document.getElementById(id);
      return node === null ? '' : (node.textContent || '');
    }).join(' ').replace(/\\s+/gu, ' ').trim();
  })()`)
}

/** Wait until the composer grew, then return the appended delta. */
async function waitForComposerDelta(page, before, timeoutMs = 15000) {
  const deadline = Date.now() + timeoutMs
  for (;;) {
    const current = await readComposerText(page)
    if (current.length > before.length) return current.slice(before.length)
    if (Date.now() > deadline) {
      throw new Error(`the composer never grew; it still holds ${JSON.stringify(current)}`)
    }
    await new Promise((resolve) => setTimeout(resolve, 100))
  }
}

/**
 * Split an inserted quote into its quoted body and its source line.
 * @param {string} delta - the text the composer gained.
 * @param {string} sourcePath - the expected workspace-relative path.
 * @returns {{quotedText: string, lineCount: number, source: boolean, text: string}} the parsed block.
 */
function parseQuoteBlock(delta, sourcePath) {
  const lines = String(delta).replace(/\r/gu, '').split('\n')
  const quoted = []
  let source = false
  for (const line of lines) {
    if (line.startsWith('> ')) quoted.push(line.slice(2))
    else if (line.trim() === `${SOURCE_LABEL}${sourcePath}`) source = true
  }
  return { quotedText: quoted.join('\n'), lineCount: quoted.length, source, text: String(delta) }
}

/** @param {{builtin: object[], takeover: object[]}} state - body state. @returns {string|null} the built-in sandbox attribute. */
function sandboxOf(state) {
  if (state.builtin.length > 0) return state.builtin[0].sandbox
  if (state.takeover.length > 0) return state.takeover[0].sandbox
  return null
}

/**
 * Read the frame rectangle and give back two points on one horizontal line.
 * @param {object} page - the page.
 * @param {string} selector - CSS selector of the iframe element.
 * @returns {Promise<{from: object, to: object}>} a left-to-right drag inside the frame.
 */
async function frameDragPoints(page, selector) {
  const rect = await page.evaluate(`(() => {
    const frame = document.querySelector(${JSON.stringify(selector)});
    if (!frame) return null;
    const box = frame.getBoundingClientRect();
    return { x: box.left, y: box.top, width: box.width, height: box.height };
  })()`)
  if (rect === null) throw new Error(`the frame ${selector} is not mounted`)
  const y = rect.y + Math.round(rect.height * 0.3)
  return {
    from: { x: rect.x + Math.round(rect.width * 0.25), y },
    to: { x: rect.x + Math.round(rect.width * 0.7), y },
  }
}

/**
 * Drive the page into an explicit state and open the HTML fixture.
 * @param {object} page - the page.
 * @param {{developerTools?: boolean, takeover?: 'on'|'off'|null}} wanted - wanted state.
 */
async function prepareHtmlPreview(page, wanted = {}) {
  if (wanted.developerTools !== undefined) await setDeveloperTools(page, wanted.developerTools)
  if (wanted.takeover !== undefined) await setHtmlTakeover(page, wanted.takeover)
  await openFilePreview(page, { directories: [FIXTURE_DIR], fileName: FIXTURE_PAGE })
}

/**
 * Poll the visible preview body state until it satisfies a predicate.
 *
 * Frame and body assertions read the *visible* state: a hidden tab keeps its
 * DOM, and a raw element count would confuse it with the preview under test.
 * @param {object} page - the page.
 * @param {(state: {takeover: object[], builtin: object[], body: number}) => boolean} predicate - acceptance test.
 * @param {string} label - failure label.
 * @param {number} [timeoutMs] - bound.
 * @returns {Promise<{takeover: object[], builtin: object[], body: number}>} the matching state.
 */
async function waitForBodyState(page, predicate, label, timeoutMs = 20000) {
  const deadline = Date.now() + timeoutMs
  let last
  for (;;) {
    last = await readHtmlBodyState(page)
    if (predicate(last)) return last
    if (Date.now() > deadline) throw new Error(`${label}; body state is ${JSON.stringify(last)}`)
    await new Promise((resolve) => setTimeout(resolve, 100))
  }
}

/** Assert the takeover body is mounted and its frame has rendered. */
async function waitForTakeoverBody(page) {
  await waitForBodyState(
    page,
    (state) => state.takeover.length === 1 && state.body >= 1,
    'the takeover body never mounted',
  )
  await waitForFrameContent(page, TAKEOVER_FRAME)
}

/** Assert the built-in body is mounted and its frame has rendered. */
async function waitForBuiltinBody(page) {
  await waitForBodyState(page, (state) => state.builtin.length >= 1, 'the built-in body never mounted')
  await waitForFrameContent(page, BUILTIN_FRAME)
}

/**
 * Come back to the fixture's preview tab after the plugin was toggled.
 *
 * The inventory switch is reached through another surface, and disabling the
 * plugin tears its client bundle down; the tab strip needs to settle before the
 * preview can be activated again.
 * @param {object} page - the page.
 */
async function returnToPreview(page) {
  await closeSettings(page)
  await waitForAppShell(page)
  assert.equal(await activatePreviewTab(page, FIXTURE_PAGE), true,
    `the ${FIXTURE_PAGE} preview tab must survive the plugin being toggled`)
  await waitForBodyState(page, (state) => state.builtin.length >= 1, 'the built-in body must come back')
}

/**
 * Re-enable the plugin after a case disabled it, without masking a real failure.
 * @param {object} page - the page.
 * @param {Error|undefined} failure - the error the case is already throwing.
 */
async function restorePlugin(page, failure) {
  try {
    await setPluginEnabled(page, PLUGIN_ID, true)
  } catch (error) {
    if (failure === undefined) throw new Error(`could not re-enable ${PLUGIN_ID} after the case: ${error.message}`)
  }
}

