/**
 * E2E layer, HTML preview takeover: E-10 … E-18 of
 * `feat-i001-f02-html-preview-takeover/core/testing-and-acceptance.md` §3.
 *
 * Plain `node:test`, zero dependencies, Node 24 globals only. Same environment
 * variables, evidence requirement and skip rules as `quote-flow.test.mjs`:
 *
 *   SIDE_QUOTE_E2E_BASE_URL       the instance URL, token included
 *   SIDE_QUOTE_E2E_CDP            `ws://…` or `http://host:port` of the browser
 *   SIDE_QUOTE_E2E_EVIDENCE_DIR   required: screenshots and their sidecars land here
 *   SIDE_QUOTE_E2E_PROFILE        required by this suite: the profile identity in the sidecars
 *
 * A missing driver, instance, evidence directory or profile makes every test
 * `skip`, never pass. Port 3081 (the operator's live instance) is refused unless
 * `SIDE_QUOTE_E2E_ALLOW_LIVE=1` is set. This file introduces no new environment
 * variable.
 *
 * Workspace fixtures the operator must provide inside the instance's workspace
 * (generated by the acceptance session; this script never creates them):
 *   samples/page.html         a self-contained page (title, paragraphs, a list)
 *   samples/page-csp.html     a page of the same shape plus
 *                             `<meta http-equiv="Content-Security-Policy" content="script-src 'none'">`
 *   samples/page-assets.html  references samples/extra.css, samples/extra.js and
 *                             samples/extra.png; used by the manual regression layer
 *                             (testing-and-acceptance §5 item 2), not asserted here
 *   samples/extra.css, samples/extra.js, samples/extra.png
 *
 * Selection drive: E-12/E-13/E-15 use CDP `Input.dispatchMouseEvent` (press →
 * several moves → release) and record `selectionDrive: 'mouse'`. The child frame
 * is consulted only to *measure* text geometry and to read the selection back;
 * the browser makes the selection itself. A run that has to fall back to a
 * synthesised `Range` must use `syntheticRangeInChildFrame` and record
 * `selectionDrive: 'synthetic-range'` — labelling it as a drag is evidence fraud
 * (testing-and-acceptance §9).
 *
 * Two measured platform behaviours shape the assertions below, and both are
 * recorded rather than worked around silently:
 *
 *   1. An opaque origin cannot be read from inside a DevTools isolated world: a
 *      sandboxed `blob:` frame reports its URL origin there, exactly like the
 *      platform's own built-in HTML frame does. E-11 therefore proves the opaque
 *      origin from the parent side, on the `message` events the bridge sends
 *      (`event.origin === 'null'`, `event.source === frame.contentWindow`).
 *   2. A quote is rendered in the composer as a structured card
 *      (`[data-composer-quote]` → `[data-quote-preview-text]`), not as Markdown
 *      text, so the excerpt is read from the card's DOM rather than parsed out of
 *      the composer's inner text.
 *
 * And one documented boundary: disabling the plugin while the takeover is
 * effective leaves the already-open preview tab with an EMPTY body until the page
 * is reloaded (`code/README.md`, HTML tradeoffs; `core/implementation.md` §9).
 * E-10 and E-18 therefore assert the teardown first, then reload the page and
 * assert the built-in renderer came back.
 *
 * Every screenshot sidecar records: git revision, instance origin/port, profile,
 * viewport, case id, takeover state (`'off' | 'on' | 'unavailable'`), selection
 * drive (`'mouse' | 'synthetic-range' | null`), the observed iframe `sandbox`
 * attribute, the developer-tools gate value when it was read, and the crop.
 */
