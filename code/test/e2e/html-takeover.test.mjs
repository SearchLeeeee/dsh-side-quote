scenario('E-10 关闭态正文等价：接管关闭与插件停用两个阶段逐字节对比', async (page, shot) => {
  let failure
  try {
    // The gate is deliberately untouched: both phases must share one gate state,
    // because the built-in renderer picks its frame variant from that state.
    await prepareHtmlPreview(page, { takeover: null })
    await waitForBuiltinBody(page)
    page.resetConsoleErrors()

    const closed = await readHtmlToggle(page)
    assert.equal(closed.present, true, 'a .html preview must show the takeover toggle (C-01)')
    assert.equal(closed.pressed, false, 'the toggle must read as off while the persisted key is absent')
    assert.equal((await readHtmlQuoteButton(page)).present, false, 'no HTML quote button while the takeover is off')
    const closedBody = await readHtmlBodyState(page)
    assert.deepEqual(closedBody.takeover, [], 'no takeover frame may exist while the takeover is off')
    assert.equal(closedBody.builtin.length, 1, 'the built-in HTML renderer must own the body')
    assert.equal(closedBody.body, 0, 'no data-side-quote-html container while the takeover is off')
    const sandboxA = sandboxOf(closedBody)
    assert.notEqual(sandboxA, null, 'the built-in frame must carry a sandbox attribute to compare')
    await shot('E-10-0-closed-header', { takeover: 'off', iframeSandbox: sandboxA })

    // The body region of the active preview: header excluded, built-in frame
    // included. Reading the built-in marker is confined to this baseline.
    const rectA = await readPreviewBodyRect(page)
    assert.equal(rectA.found, true, 'the preview must expose a measurable body region')
    assert.equal(rectA.source, 'builtin', 'the closed state must render the built-in frame')
    const clip = clipFromRect(rectA)
    const pathA = await shot('E-10-1-body-plugin-enabled', { clip, takeover: 'off', iframeSandbox: sandboxA })

    // Phase two: disable the plugin. The teardown is asserted on its own first —
    // every plugin marker gone and the console silent — because the already-open
    // tab keeps an empty body afterwards (documented boundary, see the module
    // note) and only a reload brings the built-in renderer back.
    page.resetConsoleErrors()
    await disablePlugin(page, PLUGIN_ID)
    await waitForNoPluginMarkers(page)
    assert.deepEqual(page.consoleErrors, [], `console errors while the plugin was disabled: ${JSON.stringify(page.consoleErrors)}`)

    await reloadAndReopenPreview(page)
    const disabledBody = await readHtmlBodyState(page)
    assert.equal(disabledBody.builtin.length, 1, 'the built-in HTML renderer must own the body without the plugin')
    assert.deepEqual(disabledBody.takeover, [], 'no takeover frame may survive the plugin being disabled')
    assert.equal(disabledBody.body, 0, 'no plugin body container may survive the plugin being disabled')
    const sandboxB = sandboxOf(disabledBody)
    assert.notEqual(sandboxB, null, 'the built-in frame must carry a sandbox attribute in the disabled phase')
    const rectB = await readPreviewBodyRect(page)
    assert.equal(rectB.found, true, 'the plugin-disabled phase must expose the same body region')
    const clipB = clipFromRect(rectB)
    assert.deepEqual(
      clipB,
      clip,
      `the crop must name the same region in both phases (${JSON.stringify(clip)} vs ${JSON.stringify(clipB)});`
      + ' a moved region would make the byte comparison meaningless',
    )
    const pathB = await shot('E-10-2-body-plugin-disabled', { clip, takeover: 'off', iframeSandbox: sandboxB })

    assert.equal(
      sandboxA === sandboxB,
      true,
      `both phases must mount the same built-in variant: sandbox ${JSON.stringify(sandboxA)} vs ${JSON.stringify(sandboxB)}`,
    )
    const [bytesA, bytesB] = await Promise.all([readFile(pathA), readFile(pathB)])
    const digest = (bytes) => createHash('sha256').update(bytes).digest('hex')
    const record = {
      case: 'E-10',
      clip,
      takeover: 'off',
      selectionDrive: null,
      sandboxPhaseA: sandboxA,
      sandboxPhaseB: sandboxB,
      phaseBReloaded: true,
      bytesA: bytesA.length,
      bytesB: bytesB.length,
      sha256A: digest(bytesA),
      sha256B: digest(bytesB),
      identical: bytesA.equals(bytesB),
      capturedAt: new Date().toISOString(),
    }
    await writeFile(join(config.evidenceDir, 'E-10-3-comparison.json'), `${JSON.stringify(record, null, 2)}\n`, 'utf8')
    assert.equal(
      record.identical,
      true,
      `the closed-state body must be byte-identical to the plugin-disabled body: ${JSON.stringify(record)}`,
    )
    assert.deepEqual(page.consoleErrors, [], `console errors during E-10: ${JSON.stringify(page.consoleErrors)}`)
  } catch (error) {
    failure = error
    throw error
  } finally {
    await restorePlugin(page, failure)
  }
})

scenario('E-11 开启自检：一条 info → 正文接管 → 自带消失 → 按钮置灰', async (page, shot) => {
  await setDeveloperTools(page, true)
  await prepareHtmlPreview(page, { takeover: null })
  await waitForBuiltinBody(page)
  await waitForHtmlToggle(page, { pressed: false, disabled: false })

  // The parent-side recorder is installed before the frame exists, so the
  // bootstrap's own `ready` message is captured: the only place an opaque origin
  // can be observed (see the module note).
  await startBridgeMessageRecorder(page, TAKEOVER_FRAME)
  const noticesBefore = await readNotices(page)
  page.resetConsoleErrors()
  const path = await activate(page, markedControlExpression(HTML_MARKERS.toggle), 'the HTML takeover toggle')
  assert.equal(path === 'mouse' || path === 'dom', true, `unexpected activation path ${path}`)
  await waitForHtmlToggle(page, { pressed: true, disabled: false })

  const added = await waitForAddedNotices(page, noticesBefore)
  assert.equal(added.filter(isErrorNotice).length, 0, `a successful self-check must not raise an error: ${JSON.stringify(added)}`)
  assert.equal(added.filter(isInfoNotice).length, 1, `the self-check must report exactly one info notice: ${JSON.stringify(added)}`)
  await new Promise((resolve) => setTimeout(resolve, 700))
  const settled = noticesAdded(noticesBefore, await readNotices(page))
  assert.equal(settled.filter(isInfoNotice).length, 1, `the self-check notice must not repeat: ${JSON.stringify(settled)}`)
  assert.equal(await countNotices(page, isErrorNotice), 0, 'no error notice may appear on a successful self-check')

  await waitForTakeoverBody(page)
  await waitForBodyState(page, (state) => state.builtin.length === 0, 'the built-in frame must be gone once the takeover is effective')
  const body = await readHtmlBodyState(page)
  assert.equal(body.takeover.length, 1, 'exactly one takeover frame must be mounted')
  const sandbox = sandboxOf(body)
  // The exact token list is the whole sandbox contract: the takeover frame may
  // carry `allow-scripts` and nothing else (implementation.md §5.1). Any other
  // token — same-origin access, forms, popups, top navigation, modals — fails
  // this comparison, so the forbidden ones cannot slip in unnoticed.
  assert.deepEqual(
    String(sandbox).split(/\s+/u).filter((token) => token !== ''),
    ['allow-scripts'],
    `the takeover frame must carry only allow-scripts, got ${JSON.stringify(sandbox)}`,
  )
  assert.equal(await countElements(page, TAKEOVER_BODY), 1, 'the takeover body container must be mounted once')

  const quote = await waitForHtmlQuoteButton(page, { present: true, disabled: true })
  assert.equal(quote.present, true, 'the HTML quote button must appear once the takeover is effective')
  assert.equal(quote.disabled, true, 'with no selection the HTML quote button must be disabled')

  // AC-24: the frame is opaque. Only the parent can prove it: every bridge
  // message it receives must have `origin === 'null'` and come from this frame's
  // own `contentWindow`. Reading the origin inside the frame reports the URL
  // origin even for a sandboxed blob (module note 1).
  const messages = await waitForBridgeMessages(page, { atLeast: 1, label: 'the takeover frame bootstrap' })
  const bridge = messages.filter((message) => message.channel === BRIDGE_CHANNEL)
  assert.ok(bridge.length > 0, `the bridge must report to the parent page: ${JSON.stringify(messages)}`)
  for (const message of bridge) {
    assert.equal(message.origin, 'null', `a bridge message must carry the opaque origin 'null': ${JSON.stringify(message)}`)
    assert.equal(message.fromFrame, true, `a bridge message must come from the takeover frame's contentWindow: ${JSON.stringify(message)}`)
    assert.equal(message.version, BRIDGE_VERSION, `the bridge protocol version must be ${BRIDGE_VERSION}: ${JSON.stringify(message)}`)
  }
  assert.equal(
    bridge.some((message) => message.kind === 'ready'),
    true,
    `the bootstrap must announce readiness to the parent page: ${JSON.stringify(bridge)}`,
  )

  const isolation = await readChildFrameIsolation(page, TAKEOVER_FRAME)
  assert.equal(isolation.parentReachable, false, 'page script must not reach the host document')
  assert.deepEqual(isolation.hostGlobals, [], `page script must not see any host object: ${JSON.stringify(isolation.hostGlobals)}`)
  assert.equal(isolation.canPostToParent, true, 'the bridge must be able to report to the parent window')

  assert.deepEqual(page.consoleErrors, [], `console errors during E-11: ${JSON.stringify(page.consoleErrors)}`)
  await shot('E-11-1-takeover-on', { takeover: 'on', iframeSandbox: sandbox, developerTools: true })
})

